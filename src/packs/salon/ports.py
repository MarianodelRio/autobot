"""Structural Calendar contract: a pack never chooses a calendar."""

from collections.abc import Mapping, Sequence
from datetime import datetime
from typing import Any, Protocol


class CalEvent(Protocol):
    @property
    def gcal_id(self) -> str: ...
    @property
    def summary(self) -> str: ...
    @property
    def description(self) -> str: ...
    @property
    def start(self) -> datetime: ...
    @property
    def end(self) -> datetime: ...
    @property
    def all_day(self) -> bool: ...
    @property
    def created(self) -> datetime | None: ...
    @property
    def status(self) -> str: ...
    @property
    def private(self) -> Mapping[str, str]: ...


class CalendarPort(Protocol):
    def list_events(self, start: datetime, end: datetime) -> Sequence[CalEvent]: ...
    def list_future_events(self, start: datetime) -> Sequence[CalEvent]: ...
    def get_event(self, gcal_id: str) -> CalEvent | None: ...
    def insert_event(self, event: Mapping[str, Any], gcal_id: str) -> CalEvent: ...
    def patch_description(self, gcal_id: str, fields: dict[str, str]) -> CalEvent: ...
    def patch_private(self, gcal_id: str, fields: dict[str, str]) -> CalEvent: ...
    def cancel_event(self, gcal_id: str) -> None: ...
    def list_contact_events(
        self,
        contact_id: str,
        phone: str | None,
        start: datetime,
        end: datetime,
        *,
        external_id: str | None = None,
    ) -> Sequence[CalEvent]: ...
    def check_access(self) -> None: ...
